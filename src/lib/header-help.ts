/** The description for a header on a page, or null when the registry has none. */
export function headerHelp(label: string, pathname?: string | null): string | null {
  const key = norm(label);
  if (!key) return null;
  if (pathname) {
    const route = Object.keys(PAGE)
      .filter((p) => (p === '/' ? pathname === '/' : pathname.startsWith(p)))
      .sort((a, b) => b.length - a.length)[0];
    const hit = route ? PAGE[route][key] : undefined;
    if (hit) return hit;
  }
  return GLOBAL[key] ?? null;
}

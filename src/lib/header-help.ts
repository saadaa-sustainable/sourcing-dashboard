/**
 * What every table header means, in plain words — one registry for the whole dashboard.
 *
 * Every <th> renders an (i) from here (see components/header-info.tsx and FilterTable).
 * Look-up is by the header's text, case-insensitive; a page can override a label whose
 * meaning differs there (PAGE_HEADER_HELP, keyed by route prefix). Column definitions that
 * carry their own `info:` keep it — this is the fallback that guarantees no header is mute.
 *
 * Write for the person who has never seen the page: what the column holds, where it comes
 * from, and how to read it. Trade terms (DOQ, EE, TNA, FOB, GRN, SKU, EDD) are the team's
 * daily vocabulary and are used as-is.
 */

const norm = (label: string) =>
  label
    .replace(/\s+/g, ' ')
    .replace(/[:*]+$/g, '')
    .trim()
    .toLowerCase()
    // the LIVE / FIXED tags rendered inside a header are not part of its name
    .replace(/\s+(live|fixed)$/, '');

